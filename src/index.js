/**
 * BPZILLA — edge request handling
 *
 * Two jobs, both of which need a decision made before a static file is handed
 * over: keeping /data/ from being a bulk download, and giving the archive's
 * views real URLs with their own metadata.
 *
 * ---------------------------------------------------------------------------
 * 1. /data/ — bulk-copy protection
 * ---------------------------------------------------------------------------
 * The record files are the site. `curl https://bpzilla.com/data/fast_hcr32.json`
 * returned 144,097 records in 0.41s with no browser, no referer and no session —
 * thirty-eight of those and someone has the whole 1.40M-record archive in a few
 * seconds. robots.txt says not to, but robots.txt is a request, not a control,
 * and the crawlers worth worrying about are exactly the ones that ignore it.
 *
 * This cannot make the data uncopyable. The archive is queried in the visitor's
 * browser, so the browser must receive all of it, and anything a browser can
 * receive a headless browser can receive too. A spoofed header defeats the
 * origin check outright. What the two layers here remove is the free option:
 * copying stops being one shell command and starts needing a real browser
 * driven page by page, against a per-address limit.
 *
 * ---------------------------------------------------------------------------
 * 2. Routing — real URLs for the views
 * ---------------------------------------------------------------------------
 * The site was a single URL: every model, every record and every tab shared
 * one address, one <title> and one description. Nothing could be linked to,
 * nothing survived a refresh, and search engines had exactly one page to index.
 *
 * Hash routing would have fixed the linking but not the indexing — Google
 * stopped treating fragments as separate URLs when hashbang was deprecated.
 * Real paths need a server, which the /data/ gate had already made necessary,
 * so the two arrived together.
 *
 * Each known path is served the same index.html with its <title>, description,
 * canonical and social tags rewritten to match, from the counts in
 * data/models.json (generated by extract_models.js from database.js itself, so
 * it can't drift). The client reads location.pathname and opens the matching
 * view — see App.Router in js/app.js.
 */

const DATA_PREFIX = '/data/';

// Tab paths. Keys are what a visitor types; values are the view the client
// opens. Kept deliberately short — /decoder rather than /fast-decoder-view.
const VIEW_ROUTES = {
  '/':         { view: 'database-view',     title: null },
  '/stats':    { view: 'stats-view',        title: 'Production statistics & rarity' },
  '/decoder':  { view: 'fast-decoder-view', title: 'Factory build plate decoder' },
  '/history':  { view: 'history-view',      title: 'Skyline history' },
  '/tools':    { view: 'tools-view',        title: 'Paint index & reference tools' },
  '/legends':  { view: 'legends-view',      title: 'Silvia, 180SX, Stagea & 300ZX records' }
};

// The canonical host — what every page tells a search engine it really is.
//
// gtr-registry.org is primary: it describes the content far better than
// bpzilla does, and .org suits a registry. Flipped here only after the domain
// was confirmed serving — a canonical pointing at a host that does not resolve
// tells search engines to drop the pages that do work, so the order mattered.
//
// BOTH domains canonical here, which is the point: it makes them one site
// rather than two copies of the same 1.40M records competing with each other.
// bpzilla.com keeps working and keeps its own wordmark; it just tells search
// engines where the real address is.
const SITE = 'https://gtr-registry.org';

// Hosts that wear the GTR Registry mark instead of the BPZILLA one. Same
// worker, same assets, same records — one deployment answering to both names,
// because maintaining a second copy of a 1.36M-record archive to change a logo
// would be absurd. Everything else about the page is identical by design.
const GTR_HOSTS = new Set(['gtr-registry.org', 'www.gtr-registry.org']);

