export default {
  async fetch(request, env) {
    const url = new URL(request.url);

    if (url.pathname.startsWith(DATA_PREFIX)) {
      // Nothing here is writable, so anything that isn't a read is already wrong.
      if (request.method !== 'GET' && request.method !== 'HEAD') {
        return new Response('Method not allowed', {
          status: 405,
          headers: { Allow: 'GET, HEAD', 'Cache-Control': 'no-store' }
        });
      }
      // Origin check first: it's local and free, so a request that was never
      // going to be served doesn't spend a rate-limit call on the way out.
      if (!sameOriginSignal(request, url.origin)) return refused();
      if (!(await withinRateLimit(request, env))) return tooMany();
      return env.ASSETS.fetch(request);
    }

    const route = await describeRoute(url.pathname, env);
    if (route) {
      // Every route renders the same document; only its metadata differs.
      const page = await env.ASSETS.fetch(new Request(`${url.origin}/`, request));
      if (page.ok) {
        const res = new Response(page.body, page);
        res.headers.set('Cache-Control', 'public, max-age=300');
        // Two hosts share this document, and the response now depends on which
        // one asked. Without Vary, a cache that saw one host can serve that
        // copy to the other and put the wrong wordmark on the page.
        res.headers.set('Vary', 'Host');
        const withMeta = withMetadata(res, route);
        return GTR_HOSTS.has(url.hostname) ? withGtrBrand(withMeta) : withMeta;
      }
    }

    return env.ASSETS.fetch(request);
  }
};
